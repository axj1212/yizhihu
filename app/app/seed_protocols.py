def match_protocol(protocols, diagnosis: str, dept: str, surgery: str = ""):
    text = f"{diagnosis} {surgery} {dept}"
    best = None
    for p in protocols:
        key = p.disease_key
        if key and key in text:
            return p
        if p.dept and p.dept in dept:
            best = best or p
    return best
